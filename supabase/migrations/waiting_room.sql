-- RPC: cleanup_stale_sessions
CREATE OR REPLACE FUNCTION cleanup_stale_sessions()
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
BEGIN
  -- Delete sessions older than 5 minutes
  DELETE FROM active_sessions
  WHERE last_seen < now() - interval '5 minutes';
END;
$$;

-- RPC: enter_queue
CREATE OR REPLACE FUNCTION enter_queue(p_user_id UUID)
RETURNS json
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
DECLARE
  v_max_users INT;
  v_active_count INT;
  v_user_active BOOLEAN;
  v_queue_pos INT;
  v_setting_val JSONB;
BEGIN
  -- Cleanup first
  PERFORM cleanup_stale_sessions();

  -- Get max users from system_settings
  SELECT setting_value INTO v_setting_val FROM system_settings WHERE setting_key = 'max_concurrent_users';
  
  -- Handle jsonb to int conversion (remove quotes if needed)
  IF v_setting_val IS NULL THEN 
    v_max_users := 50; 
  ELSE
    v_max_users := (v_setting_val#>>'{}')::INT;
  END IF;

  -- Check if user is already active
  SELECT EXISTS(SELECT 1 FROM active_sessions WHERE user_id = p_user_id) INTO v_user_active;
  
  IF v_user_active THEN
    UPDATE active_sessions SET last_seen = now() WHERE user_id = p_user_id;
    RETURN json_build_object('status', 'active');
  END IF;

  -- Check active count
  SELECT count(*) INTO v_active_count FROM active_sessions;

  IF v_active_count < v_max_users THEN
    -- Allow entry
    INSERT INTO active_sessions (user_id) VALUES (p_user_id)
    ON CONFLICT (user_id) DO UPDATE SET last_seen = now();
    
    -- Remove from queue if exists
    DELETE FROM waiting_queue WHERE user_id = p_user_id;
    
    RETURN json_build_object('status', 'active');
  ELSE
    -- Add to queue
    INSERT INTO waiting_queue (user_id) VALUES (p_user_id)
    ON CONFLICT (user_id) DO NOTHING;
    
    -- Get position
    SELECT count(*) + 1 INTO v_queue_pos FROM waiting_queue 
    WHERE created_at <= (SELECT created_at FROM waiting_queue WHERE user_id = p_user_id);
    
    RETURN json_build_object('status', 'waiting', 'position', v_queue_pos);
  END IF;
END;
$$;

-- RPC: heartbeat
CREATE OR REPLACE FUNCTION heartbeat(p_user_id UUID)
RETURNS json
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
DECLARE
  v_updated INT;
BEGIN
  UPDATE active_sessions SET last_seen = now() WHERE user_id = p_user_id;
  GET DIAGNOSTICS v_updated = ROW_COUNT;
  
  IF v_updated > 0 THEN
    RETURN json_build_object('status', 'active');
  ELSE
    RETURN json_build_object('status', 'expired');
  END IF;
END;
$$;

-- RPC: leave_queue
CREATE OR REPLACE FUNCTION leave_queue(p_user_id UUID)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
BEGIN
  DELETE FROM active_sessions WHERE user_id = p_user_id;
  DELETE FROM waiting_queue WHERE user_id = p_user_id;
END;
$$;
